#!/usr/bin/env python3
"""Compute board.runtime overrides from custom.txt (phase 2 M4/M5).

Replaces the historical `sed -i` chain inside `customize_image`, which mutated
board.txt in place. The output contains only the variables whose values differ
from the board file, so `board.txt` stays a pristine copy of config/<board>.toml.

The rules are a direct transcription of lib/function/staging::customize_image.
Equivalence with the old sed chain is checked by
boards/z96a-v2/tests/test_board_runtime.py.

Usage: gen-board-runtime.py <board.txt> <custom.txt>
"""

import re
import sys

VAR = re.compile(r'^([A-Z][A-Z0-9_]*)="(.*)"$')


def read_vars(path):
    values = {}
    for line in open(path, encoding="utf-8", errors="replace"):
        match = VAR.match(line.rstrip("\n"))
        if match:
            values[match.group(1)] = match.group(2)
    return values


def truthy(value):
    return value == "true"


def compute(board, custom):
    """Return {var: new_value} for every variable the old sed chain would change."""
    changed = {}

    def set_var(name, value):
        if board.get(name) != value:
            changed[name] = value

    family = board.get("FAMILY", "")
    family_ext = board.get("FAMILY_EXT", "")

    # FSTYPE btrfs/xfs cannot boot directly, so force a boot partition.
    if custom.get("FSTYPE", "") in ("btrfs", "xfs"):
        if board.get("P_VALUE") == "p1":
            set_var("P_VALUE", "p2")

    # BOOTCMD (non-broadcom)
    if family != "broadcom":
        if truthy(custom.get("ENABLE_BOOTCMD")) and not truthy(custom.get("ENABLE_PETITBOOT")):
            if board.get("EXTLINUX") == "true":
                set_var("EXTLINUX", "false")
            if board.get("BOOTCMD") == "false":
                set_var("BOOTCMD", "true")

    # BOOT_EXT4
    if truthy(custom.get("ENABLE_BOOT_EXT4")):
        if board.get("BOOT_EXT4") == "false":
            set_var("BOOT_EXT4", "true")
        if board.get("P_VALUE") == "p1":
            set_var("P_VALUE", "p2")

    # BOOT_VFAT
    if truthy(custom.get("ENABLE_BOOT_VFAT")):
        if board.get("BOOT_VFAT") == "false":
            set_var("BOOT_VFAT", "true")
        if board.get("P_VALUE") == "p1":
            set_var("P_VALUE", "p2")

    # EFI (non-broadcom)
    if family != "broadcom" and truthy(custom.get("ENABLE_EFI")):
        if board.get("EFI") == "false":
            set_var("EFI", "true")
        if board.get("BOOT_VFAT") == "false":
            set_var("BOOT_VFAT", "true")
        if board.get("P_VALUE") == "p1":
            set_var("P_VALUE", "p2")
        if board.get("EXTLINUX") == "true":
            set_var("EXTLINUX", "false")
        if board.get("BOOTCMD") == "true":
            set_var("BOOTCMD", "false")
        if board.get("BOOTINI") == "true":
            set_var("BOOTCMD", "false")
        if family == "rockchip" and board.get("GPT") == "false":
            set_var("GPT", "true")

    # Petitboot (odroid family)
    if truthy(custom.get("ENABLE_PETITBOOT")) and family_ext == "odroid":
        if board.get("P_VALUE") == "p1":
            set_var("P_VALUE", "p2")
        if board.get("EXTLINUX") == "true":
            set_var("EXTLINUX", "false")
        if board.get("PETITBOOT") == "false":
            set_var("PETITBOOT", "true")

    return changed


def main():
    if len(sys.argv) != 3:
        print("usage: gen-board-runtime.py <board.txt> <custom.txt>", file=sys.stderr)
        return 2

    board = read_vars(sys.argv[1])
    custom = read_vars(sys.argv[2])
    changed = compute(board, custom)

    print("# GENERATED by boards/<board>/tools/gen-board-runtime.py")
    print("# Overrides applied after board.txt; board.txt itself is never edited.")
    print("# Values below are the effective result for every key the rules touch.")
    affected = ("P_VALUE", "EXTLINUX", "BOOTCMD", "BOOT_EXT4", "BOOT_VFAT",
                "EFI", "GPT", "PETITBOOT")
    for name in affected:
        if name in board or name in changed:
            value = changed.get(name, board.get(name, ""))
            print(f'{name}="{value}"')
    return 0


if __name__ == "__main__":
    sys.exit(main())
